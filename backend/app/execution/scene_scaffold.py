"""The scene runner for 3D projects (js/main.js), generated from the project plan instead of written by a model.

Models write every 3D object (one module each), the pages, the styles and js/scene-extras.js (custom lighting,
effects, animation and interactions). Live builds showed that the wiring in between — renderer, camera, controls,
loop, start-up, element ids — is exactly where free and local models fail, so this file is plain, tested code:
it imports every object module, calls its create function, scales each object to a comparable size, spreads them
out, frames the camera on all of them, runs their update() animations and starts itself when the page loads.
"""

import json
from typing import Dict, List

TEMPLATE = """// Scene runner generated by City AI from the project plan. The objects it shows are written in js/objects/,
// custom lighting/effects/interactions in js/scene-extras.js.
// REQ:{scene_reqs}
import * as THREE from 'three';
import {{ OrbitControls }} from 'three/addons/controls/OrbitControls.js';
{imports}
{extras_import}
const OBJECTS = {objects};
const MODULES = [{module_list}];

function factoryOf(mod) {{
  const fns = Object.entries(mod).filter(([key, value]) => typeof value === 'function' && key !== 'update');
  const named = fns.find(([key]) => /^(create|build|make)/i.test(key));
  const pick = named || fns.find(([key]) => key === 'default') || fns[0];
  return pick ? pick[1] : null;
}}

function hostElement() {{
  let host = document.getElementById('scene') || document.querySelector('[data-scene], #scene-container, #viewport, .scene-container, canvas');
  if (!host) {{
    host = document.createElement('div');
    host.id = 'scene';
    (document.querySelector('main') || document.body).prepend(host);
  }}
  return host;
}}

function start() {{
  let host = hostElement();
  let canvas = null;
  if (host.tagName === 'CANVAS') {{ canvas = host; host = canvas.parentElement || document.body; }}
  if (host.clientHeight < 240) host.style.minHeight = '70vh';
  if (!host.style.position) host.style.position = 'relative';

  const renderer = new THREE.WebGLRenderer({{ canvas: canvas || undefined, antialias: true }});
  renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 2));
  renderer.outputColorSpace = THREE.SRGBColorSpace;
  if (!canvas) {{
    renderer.domElement.style.display = 'block';
    host.appendChild(renderer.domElement);
  }}
  const scene = new THREE.Scene();
  scene.background = new THREE.Color(0x05070d);
  const camera = new THREE.PerspectiveCamera(50, 1, 0.1, 5000);
  scene.add(new THREE.HemisphereLight(0xe6eeff, 0x2a3040, 1.8));
  const sun = new THREE.DirectionalLight(0xffffff, 3.2);
  sun.position.set(10, 16, 8);
  scene.add(sun);
  const controls = new OrbitControls(camera, renderer.domElement);
  controls.enableDamping = true;

  const placed = [];
  const updates = [];
  OBJECTS.forEach((info, i) => {{
    const make = factoryOf(MODULES[i]);
    if (!make) {{ console.error(info.path + ': the module exports no create function'); return; }}
    let obj;
    try {{ obj = make(THREE); }} catch (err) {{ console.error(info.path + ': ' + (err && err.message || err)); return; }}
    if (!obj || !obj.isObject3D) {{ console.error(info.path + ': the create function did not return a THREE.Object3D'); return; }}
    if (!obj.name) obj.name = info.name;
    const size = new THREE.Box3().setFromObject(obj).getSize(new THREE.Vector3());
    const largest = Math.max(size.x, size.y, size.z);
    if (largest > 0 && isFinite(largest)) obj.scale.multiplyScalar(6 / largest);
    const angle = (i / Math.max(OBJECTS.length, 1)) * Math.PI * 2;
    const radius = OBJECTS.length > 1 ? 4 + OBJECTS.length * 1.6 : 0;
    obj.position.x += Math.cos(angle) * radius;
    obj.position.z += Math.sin(angle) * radius;
    // objects stand on the ground unless their module placed them in the air (planets, satellites...)
    const floats = (MODULES[i].floating === true) || /planet|moon|satellite|orbit|star|sun|cloud|drone|ship|station/i.test(info.name);
    const after = new THREE.Box3().setFromObject(obj);
    if (isFinite(after.min.y)) obj.position.y -= after.min.y;
    if (floats) obj.position.y += 7;
    scene.add(obj);
    placed.push(obj);
    const update = MODULES[i].update || (obj.userData && obj.userData.update);
    if (typeof update === 'function') updates.push((t, dt) => (update.length >= 2 ? update(obj, t, dt) : update(t, dt)));
  }});

  const ground = new THREE.Mesh(new THREE.CircleGeometry(60, 64), new THREE.MeshStandardMaterial({{ color: 0x10141c, roughness: 0.95 }}));
  ground.rotation.x = -Math.PI / 2;
  ground.position.y = -0.01;
  scene.add(ground);

  const all = new THREE.Box3();
  placed.forEach(o => all.expandByObject(o));
  const center = all.isEmpty() ? new THREE.Vector3() : all.getCenter(new THREE.Vector3());
  const span = all.isEmpty() ? 10 : all.getSize(new THREE.Vector3()).length();
  camera.position.set(center.x + span * 0.35, center.y + span * 0.28, center.z + span * 0.62);
  controls.target.copy(center);

  const ctx = {{ THREE, scene, camera, renderer, controls, objects: placed, host }};
  if (extras && typeof extras.setup === 'function') {{
    try {{ extras.setup(ctx); }} catch (err) {{ console.error('js/scene-extras.js: ' + (err && err.message || err)); }}
  }}

  function resize() {{
    const w = host.clientWidth || window.innerWidth;
    const h = host.clientHeight || Math.round(window.innerHeight * 0.7);
    renderer.setSize(w, h, !canvas);
    camera.aspect = w / Math.max(h, 1);
    camera.updateProjectionMatrix();
  }}
  window.addEventListener('resize', resize);
  resize();

  const clock = new THREE.Clock();
  renderer.setAnimationLoop(() => {{
    const dt = clock.getDelta();
    const t = clock.elapsedTime;
    for (const step of updates) {{ try {{ step(t, dt); }} catch (err) {{ /* one bad animation must not stop the scene */ }} }}
    if (extras && typeof extras.update === 'function') {{ try {{ extras.update(t, dt, ctx); }} catch (err) {{}} }}
    controls.update();
    renderer.render(scene, camera);
  }});
}}

if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
else start();
"""


def build_main_js(objects: List[Dict[str, str]], scene_req_ids: List[str], with_extras: bool) -> str:
    """objects: [{"path": "js/objects/rocket.js", "name": "rocket"}] in display order."""
    imports = "\n".join(f"import * as m{i} from './{o['path'][len('js/'):]}';" for i, o in enumerate(objects))
    return TEMPLATE.format(
        scene_reqs="\n// REQ:".join(scene_req_ids) or "scene",
        imports=imports,
        extras_import="import * as extras from './scene-extras.js';" if with_extras else "const extras = null;",
        objects=json.dumps([{"path": o["path"], "name": o["name"]} for o in objects]),
        module_list=", ".join(f"m{i}" for i in range(len(objects))),
    )
